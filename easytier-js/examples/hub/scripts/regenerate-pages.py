#!/usr/bin/env python3
"""把 public/*.html 打包成 src/pages.ts（Worker 直接返回的 HTML 就来自这里）。

为什么需要这一步：HTML 是在 Worker 脚本里以字符串形式返回的（不用 Workers Static
Assets），而 src/worker.ts 只 `import { LOGIN_HTML, DASHBOARD_HTML } from "./pages"`。
因此：

    public/index.html  ──┐
    public/login.html  ──┴─→ src/pages.ts ──→ wrangler deploy

只改 public/*.html 而不跑本脚本，线上看到的仍是旧内容 —— 这类"两份 HTML 漂移"的
bug 在 review 里几乎看不出来，所以生成脚本必须入库、必须能逐字节复现。

用法：
    python3 scripts/regenerate-pages.py          生成（或 npm run gen:pages）
    python3 scripts/regenerate-pages.py --check  只校验，不一致则退出码 1（或 npm run check:pages）

--check 给 CI 用：谁改了 public/*.html 却没重新生成 src/pages.ts，流水线直接红，
不用等线上出现"改了没生效"这种诡异现象。
"""
from __future__ import annotations

import json
import pathlib
import re
import sys

HUB = pathlib.Path(__file__).resolve().parents[1]
OUT = HUB / "src" / "pages.ts"

HEADER = (
    "// GENERATED by scripts/regenerate-pages.py from public/*.html.\n"
    "// Do not edit by hand; edit public/index.html / public/login.html and run `npm run gen:pages`.\n"
)


# 只做"无损压缩"：删 HTML 注释、行尾空白、连续空行和标签之间的缩进。
# 绝不碰 <script>/<style>/<pre>/<textarea>（内容可能对空白敏感），也不折叠标签之间的
# 空格（`</span> <span>` 里的那个空格是可见的，折叠会改版式）。
PROTECTED = re.compile(r"(<(script|style|pre|textarea)\b[^>]*>)(.*?)(</\2>)", re.S | re.I)
COMMENT = re.compile(r"<!--(?!\[if).*?-->", re.S)


def _minify_chunk(chunk: str) -> str:
    chunk = COMMENT.sub("", chunk)
    chunk = re.sub(r"[ \t]+\n", "\n", chunk)
    chunk = re.sub(r"\n{2,}", "\n", chunk)
    chunk = re.sub(r">[ \t]*\n[ \t]*<", ">\n<", chunk)
    return chunk


def minify_html(html: str) -> str:
    out: list[str] = []
    last = 0
    for m in PROTECTED.finditer(html):
        out.append(_minify_chunk(html[last:m.start()]))
        out.append(m.group(0))
        last = m.end()
    out.append(_minify_chunk(html[last:]))
    return "".join(out)


def build() -> str:
    login_raw = (HUB / "public" / "login.html").read_text(encoding="utf-8")
    dashboard_raw = (HUB / "public" / "index.html").read_text(encoding="utf-8")
    login = minify_html(login_raw)
    dashboard = minify_html(dashboard_raw)
    print(
        f"minified: login {len(login_raw)}→{len(login)} "
        f"({100 - round(len(login) * 100 / len(login_raw))}% off), "
        f"dashboard {len(dashboard_raw)}→{len(dashboard)} "
        f"({100 - round(len(dashboard) * 100 / len(dashboard_raw))}% off)",
        file=sys.stderr,
    )
    return (
        HEADER
        + "export const LOGIN_HTML = " + json.dumps(login, ensure_ascii=False) + ";\n"
        + "export const DASHBOARD_HTML = " + json.dumps(dashboard, ensure_ascii=False) + ";\n"
    )


def first_diff(a: str, b: str) -> str:
    n = min(len(a), len(b))
    i = next((k for k in range(n) if a[k] != b[k]), n)
    return (
        f"first difference at char {i} (generated {len(a)} / on disk {len(b)})\n"
        f"  generated: {a[max(0, i - 60):i + 60]!r}\n"
        f"  on disk  : {b[max(0, i - 60):i + 60]!r}"
    )


def main() -> int:
    generated = build()
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""

    if "--check" in sys.argv[1:]:
        if generated == current:
            print(f"{OUT.relative_to(HUB)} is up to date ({len(generated)} chars)")
            return 0
        print(f"ERROR: {OUT.relative_to(HUB)} does not match public/*.html", file=sys.stderr)
        print(first_diff(generated, current), file=sys.stderr)
        print("Run `python3 scripts/regenerate-pages.py` (or `npm run gen:pages`) and commit the result.", file=sys.stderr)
        return 1

    OUT.write_text(generated, encoding="utf-8")
    print(f"wrote {OUT.relative_to(HUB)} ({len(generated)} chars)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
